def main() -> None:
    if not TEMPLATE_PATH.exists():
        raise FileNotFoundError(f"Template not found: {TEMPLATE_PATH}")

    doc = Document(str(TEMPLATE_PATH))
    paragraphs = [p for p in doc.paragraphs if p.text.strip()]
    content = CONTENT[: len(paragraphs)]

    for paragraph, text in zip(paragraphs, content):
        paragraph.text = text

    for text in CONTENT[len(content):]:
        doc.add_paragraph(text)

    doc.core_properties.title = CONTENT[0]
    doc.core_properties.subject = "需求分析与系统设计"
    doc.core_properties.comments = "根据 DietApp 项目代码自动生成"
    doc.save(str(OUTPUT_PATH))
    print(OUTPUT_PATH)


if __name__ == "__main__":
    main()
